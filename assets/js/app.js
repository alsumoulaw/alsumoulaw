/* نطاقات بريد إلكتروني موثوقة (Gmail وما شابهها من مزودين معروفين) */
const trustedEmailDomains = ["gmail.com", "googlemail.com", "outlook.com", "hotmail.com", "yahoo.com", "icloud.com", "live.com"];
function isTrustedEmail(email) {
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) return false;
  const domain = email.split("@")[1].toLowerCase();
  return trustedEmailDomains.includes(domain);
}

/* التأكد من أن النص المُدخل هو وصف حقيقي وليس حروفاً أو أرقاماً عشوائية */
function isMeaningfulText(text, minWords, minLength) {
  const trimmed = (text || "").trim();
  if (trimmed.length < minLength) return false;
  const compact = trimmed.replace(/\s+/g, "");
  /* رفض النص المكرر من حرف واحد مثل "اااااا" أو "111111" */
  if (/^(.)\1{3,}$/.test(compact)) return false;
  const words = trimmed.split(/\s+/).filter(Boolean);
  if (words.length < minWords) return false;
  const letterCount = (trimmed.match(/[A-Za-zأ-ي\u0600-\u06FF]/g) || []).length;
  if (letterCount < compact.length * 0.5) return false;
  return true;
}

/* التأكد من أن الاسم كامل (اسمين على الأقل) وبحروف فقط */
function isValidFullName(name) {
  const trimmed = (name || "").trim();
  if (trimmed.length < 3 || /[0-9]/.test(trimmed)) return false;
  const parts = trimmed.split(/\s+/).filter(Boolean);
  if (parts.length < 2) return false;
  return parts.every(p => p.length >= 2);
}

